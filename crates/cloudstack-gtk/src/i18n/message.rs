    pub(crate) fn args(&self) -> Option<HashMap<Cow<'static, str>, FluentValue<'static>>> {
        let args = match self {
            Self::GitSaveBeforeAction { count } | Self::GitSaveBeforeActionTooltip { count } => {
                HashMap::from([(Cow::Borrowed("count"), FluentValue::from(*count))])
            }
            Self::ProjectOpenedStatus { count } => {
                HashMap::from([(Cow::Borrowed("count"), FluentValue::from(*count))])
            }
            Self::WindowTitle { folder } => {
                HashMap::from([(Cow::Borrowed("folder"), FluentValue::from(folder.clone()))])
            }
            Self::CreateArticleDefaultName { extension }
            | Self::CreateArticlePlaceholder { extension } => HashMap::from([(
                Cow::Borrowed("extension"),
                FluentValue::from(extension.clone()),
            )]),
            Self::DeleteArticleBody { path } => {
                HashMap::from([(Cow::Borrowed("path"), FluentValue::from(path.clone()))])
            }
            Self::MissingContentDirectoryBody { content_dir } => HashMap::from([(
                Cow::Borrowed("content_dir"),
                FluentValue::from(content_dir.clone()),
            )]),
            Self::ProjectDirectoryLabel { path } => {
                HashMap::from([(Cow::Borrowed("path"), FluentValue::from(path.clone()))])
            }
            Self::RemoveTagTooltip { tag } => {
                HashMap::from([(Cow::Borrowed("tag"), FluentValue::from(tag.clone()))])
            }
            Self::FieldTitle { name } | Self::RequiredFieldTitle { name } => {
                HashMap::from([(Cow::Borrowed("name"), FluentValue::from(name.clone()))])
            }
            _ => return None,
        };
        Some(args)
    }
